import fs from 'node:fs';
import { execSync } from 'node:child_process';
import { launch, BASE, OUT, sleep, clickText, menu, setDownloads, waitForFile, assert } from './lib.mjs';
const dl = OUT + '/downloads6'; fs.rmSync(dl, { recursive: true, force: true });
const browser = await launch(); const page = await browser.newPage();
const errs = []; page.on('pageerror', (e) => errs.push(e.message)); page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await setDownloads(page, dl);
await page.goto(BASE, { waitUntil: 'networkidle0' });
await clickText(page, 'button', 'New document'); await page.waitForSelector('.pw-prose'); await page.click('.pw-prose');
await page.evaluate(() => { document.execCommand('insertText', false, 'Привет мир. Γειά σου κόσμε. Café naïve. 你好世界. مرحبا بالعالم'); });
await sleep(1200);
await menu(page, 'File', 'PDF document (.pdf)');
const pdf = await waitForFile(dl, '.pdf', 90000);
const size = fs.statSync(pdf).size;
const txt = execSync(`pdftotext "${pdf}" -`).toString();
console.log('PDF bytes:', size); console.log(JSON.stringify(txt));
assert(txt.includes('Привет') && txt.includes('мир'), 'Cyrillic selectable');
assert(txt.includes('Γειά') , 'Greek selectable');
assert(txt.includes('Café'), 'Latin accents selectable');
assert(/مرحبا|ﻣﺮﺣﺒﺎ|ابحرم/.test(txt), 'Arabic text present');
console.log('errors:', errs);
await browser.close();
