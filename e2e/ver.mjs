import { launch, watch, BASE, sleep, clickText, menu, assert } from './lib.mjs';
const browser = await launch(); const page = await browser.newPage();
const log = []; watch(page, log);
await page.goto(BASE, { waitUntil: 'networkidle0' });
await clickText(page, 'button', 'New document');
await page.waitForSelector('.pw-prose'); await page.click('.pw-prose');
await page.keyboard.type('Alpha original text');
await sleep(1200);
await menu(page, 'File', 'Version history…');
await page.waitForSelector('.version-save input');
await page.type('.version-save input', 'First draft');
await clickText(page, 'button', 'Save version now'); await sleep(600);
assert((await page.$$('.version-item')).length === 1, 'one version listed');
await page.click('.version-item'); await sleep(400);
assert((await page.$eval('.version-preview', (e) => e.textContent)).includes('Alpha original'), 'preview shows the snapshot');
await page.keyboard.press('Escape'); await sleep(300);
await page.click('.pw-prose'); await page.keyboard.down('Control'); await page.keyboard.press('a'); await page.keyboard.up('Control');
await page.keyboard.type('Totally different'); await sleep(1200);
await menu(page, 'File', 'Version history…'); await page.waitForSelector('.version-item');
const items = await page.$$('.version-item');
let named; for (const it of items) { if ((await it.evaluate((e) => e.textContent)).includes('First draft')) named = it; }
await named.click(); await sleep(300);
await clickText(page, 'button', 'Restore this version'); await sleep(1200);
assert((await page.$eval('.pw-prose', (e) => e.textContent)).includes('Alpha original'), 'editor content restored');
assert(!(await page.$('.dialog')), 'dialog closed');
await page.reload({ waitUntil: 'networkidle0' }); await page.waitForSelector('.pw-prose');
assert((await page.$eval('.pw-prose', (e) => e.textContent)).includes('Alpha original'), 'restored content persisted after reload');
await menu(page, 'File', 'Version history…'); await page.waitForSelector('.version-item');
const texts = await page.$$eval('.version-item', (els) => els.map((e) => e.textContent));
assert(texts.some((t) => t.includes('Before restore')), 'replaced text kept as "Before restore": ' + texts.join(' | '));
console.log('LOG', log);
await browser.close();
