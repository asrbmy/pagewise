import { launch, watch, BASE, OUT, sleep, clickText, assert } from './lib.mjs';
const browser = await launch();
const page = await browser.newPage();
await page.setViewport({ width: 390, height: 844, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const log = []; watch(page, log);
await page.goto(BASE, { waitUntil: 'networkidle0' });
await clickText(page, 'button', 'New document');
await page.waitForSelector('.pw-prose');
await page.tap('.pw-prose');
await page.keyboard.type('Readable text on a phone screen. '.repeat(6));
await sleep(500);
const m = await page.evaluate(() => ({ sw: document.documentElement.scrollWidth, iw: innerWidth, sheet: Math.round(document.querySelector('.sheet-wrap').getBoundingClientRect().width), fs: getComputedStyle(document.querySelector('.pw-prose')).fontSize, status: document.querySelector('.statusbar').innerText.replace(/\s+/g,' ') }));
console.log(m);
assert(m.sw <= m.iw + 1 && m.sheet <= m.iw, 'no overflow in reflow view');
await page.screenshot({ path: OUT + '/mobile-editor2.png' });
await page.select('select[aria-label="Zoom"]', '1');
await sleep(300);
const sw2 = await page.evaluate(() => ({ page: document.documentElement.scrollWidth }));
console.log('100% zoom page width scrolls inside canvas, page scrollWidth:', sw2.page);
await page.goto(BASE, { waitUntil: 'networkidle0' });
await page.screenshot({ path: OUT + '/mobile-home2.png' });
console.log(log);
await browser.close();
