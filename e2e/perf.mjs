import { launch, watch, BASE, sleep, assert, OUT } from './lib.mjs';
import fs from 'node:fs';
const N = 3000;
const md = ['# Big document', ...Array.from({ length: N }, (_, i) => `Paragraph ${i}: ${'lorem ipsum dolor sit amet '.repeat(6)}`)].join('\n\n');
fs.writeFileSync(OUT + '/big.md', md);
const browser = await launch(); const page = await browser.newPage();
const log = []; watch(page, log); page.on('dialog', (d) => d.accept());
await page.goto(BASE, { waitUntil: 'networkidle0' });
const t0 = Date.now();
await (await page.$('input[type=file]')).uploadFile(OUT + '/big.md');
await page.waitForSelector('.pw-prose', { timeout: 60000 });
await page.waitForFunction(() => document.querySelectorAll('.pw-prose p').length > 2500, { timeout: 60000 });
const openMs = Date.now() - t0;
await sleep(3000);
await page.click('.pw-prose p'); await page.keyboard.down('Control'); await page.keyboard.press('End'); await page.keyboard.up('Control');
const t1 = Date.now();
await page.keyboard.type('typing latency probe text', { delay: 0 });
await page.waitForFunction(() => document.querySelector('.pw-prose').textContent.includes('typing latency probe text'), { timeout: 60000 });
const typeMs = Date.now() - t1;
console.log(`open ${openMs} ms, type 25 chars ${typeMs} ms`);
assert(openMs < 30000, `opens ${N} paragraphs in ${openMs} ms`);
assert(typeMs < 8000, `typing stays responsive: ${typeMs} ms for 25 characters`);
await browser.close();
