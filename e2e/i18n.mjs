import { launch, watch, BASE, sleep, clickText, assert } from './lib.mjs';
const browser = await launch(); const page = await browser.newPage();
const log = []; watch(page, log); page.on('dialog', (d) => d.accept());
await page.goto(BASE, { waitUntil: 'networkidle0' });
await page.select('.lang-select', 'es'); await sleep(400);
assert(await page.evaluate(() => document.body.innerText.includes('Tus documentos')), 'home in Spanish');
assert(await page.evaluate(() => document.documentElement.lang === 'es'), 'html lang es');
await clickText(page, 'button', 'Nuevo documento', { exact: false }).catch(async () => { await clickText(page, 'button', 'New document'); });
await page.waitForSelector('.pw-prose');
const bar = await page.$$eval('.menubar [role=menuitem]', (e) => e.map((x) => x.textContent.trim()));
console.log(bar);
assert(bar.includes('Archivo') && bar.includes('Insertar'), 'editor menus in Spanish');
await page.reload({ waitUntil: 'networkidle0' }); await page.waitForSelector('.pw-prose');
assert((await page.$$eval('.menubar [role=menuitem]', (e) => e.map((x) => x.textContent.trim()))).includes('Archivo'), 'persists');
await page.evaluate(() => { const k='pagewise:prefs'; const p=JSON.parse(localStorage.getItem(k)); p.language='auto'; localStorage.setItem(k, JSON.stringify(p)); });
await page.reload({ waitUntil: 'networkidle0' }); await page.waitForSelector('.pw-prose');
assert((await page.$$eval('.menubar [role=menuitem]', (e) => e.map((x) => x.textContent.trim()))).includes('File'), 'auto -> English for en-US');
console.log('LOG', log);
await browser.close();
