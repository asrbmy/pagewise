import { launch, watch, BASE, sleep, clickText, menu, assert } from './lib.mjs';
const browser = await launch(); const page = await browser.newPage();
const log = []; watch(page, log); page.on('dialog', (d) => d.accept());
await page.goto(BASE, { waitUntil: 'networkidle0' });
await clickText(page, 'button', 'New document'); await page.waitForSelector('.pw-prose'); await page.click('.pw-prose');
await page.keyboard.type('# Big title'); await page.keyboard.press('Enter'); await page.keyboard.type('Body text here'); await sleep(500);
const before = await page.evaluate(() => ({ h1: getComputedStyle(document.querySelector('.pw-prose h1')).fontSize, p: getComputedStyle(document.querySelector('.pw-prose p')).color }));
await menu(page, 'File', 'Document styles…'); await page.waitForSelector('.styles-row');
const rows = await page.$$('.styles-row');
const h1 = rows[1];
await (await h1.$('input[type=number]')).type('40');
await h1.$eval('input[type=color]', (el) => { const set = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set; set.call(el, '#c00000'); el.dispatchEvent(new Event('input', { bubbles: true })); });
await clickText(page, '.dialog button', 'Apply'); await sleep(600);
const after = await page.evaluate(() => { const c = getComputedStyle(document.querySelector('.pw-prose h1')); return { size: c.fontSize, color: c.color }; });
assert(after.size === '53.3333px' && after.color === 'rgb(192, 0, 0)', 'heading restyled: ' + JSON.stringify(after) + ' was ' + before.h1);
await page.reload({ waitUntil: 'networkidle0' }); await page.waitForSelector('.pw-prose h1');
const kept = await page.$eval('.pw-prose h1', (e) => getComputedStyle(e).color);
assert(kept === 'rgb(192, 0, 0)', 'styles persist after reload');
console.log('LOG', log);
await browser.close();
